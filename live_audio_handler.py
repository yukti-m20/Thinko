"""
live_audio_handler.py — Full-duplex audio queue manager and playback controller.

Coordinates:
  - Input stream: Mic / ESP32 audio (16 kHz PCM) -> Gemini Live
  - Output stream: Gemini Live audio (24 kHz PCM) -> Playback queue -> Speaker / ESP32
  - Pause vs Voice Interruption logic (cleanly separated):
      * Pause: stops sending audio to the speaker, preserves queued chunks,
               and gates mic input to avoid accidental new turns.
      * Resume: continues streaming remaining queued chunks from where paused.
      * Voice Interruption: immediately flushes playback queue, increments
               response_id, and triggers cancellation signal to ESP32.
"""

from __future__ import annotations

import asyncio
import logging
import time
from typing import Callable, Optional

logger = logging.getLogger("thinko.audio")


class LiveAudioHandler:
    """
    Manages audio queues and stream state for Gemini Live full-duplex operation.
    """

    def __init__(
        self,
        on_send_output_chunk: Optional[Callable[[bytes, int], None]] = None,
        on_state_change: Optional[Callable[[str], None]] = None,
        max_output_queue_size: int = 150,  # ~15-20 seconds max buffer
    ):
        self.on_send_output_chunk = on_send_output_chunk or (lambda chunk, r_id: None)
        self.on_state_change = on_state_change or (lambda state: None)

        self._output_queue: asyncio.Queue[tuple[bytes, int]] = asyncio.Queue(maxsize=max_output_queue_size)
        self._is_paused = False
        self._is_playing = False
        self._current_response_id = 1
        self._worker_task: Optional[asyncio.Task] = None
        self._running = False

        # Diagnostic metrics
        self.total_chunks_received = 0
        self.total_chunks_played = 0
        self.dropped_chunks_on_interruption = 0
        self.queue_overflow_drops = 0

    @property
    def is_paused(self) -> bool:
        return self._is_paused

    @property
    def is_playing(self) -> bool:
        return self._is_playing and not self._is_paused

    def start(self) -> None:
        """Start the background playback dispatcher."""
        self._running = True
        self._worker_task = asyncio.create_task(self._playback_dispatcher())

    def stop(self) -> None:
        """Stop playback dispatcher."""
        self._running = False
        if self._worker_task:
            self._worker_task.cancel()

    def handle_incoming_audio_chunk(self, chunk: bytes, response_id: int) -> None:
        """
        Receives an audio chunk generated by Gemini Live and adds it to the playback queue.
        Discards chunks if they belong to an older/canceled response_id.
        """
        if response_id < self._current_response_id:
            return

        self.total_chunks_received += 1
        try:
            self._output_queue.put_nowait((chunk, response_id))
        except asyncio.QueueFull:
            self.queue_overflow_drops += 1
            logger.warning("Output audio queue full; dropping oldest chunk to maintain real-time pacing.")
            try:
                self._output_queue.get_nowait()
                self._output_queue.put_nowait((chunk, response_id))
            except Exception:
                pass

    def pause_playback(self) -> None:
        """
        Pause playback without losing audio in the queue.
        Also gates mic so background noise does not trigger new turns while paused.
        """
        if not self._is_paused:
            self._is_paused = True
            self.on_state_change("paused")
            logger.info("Audio playback PAUSED (buffer preserved).")

    def resume_playback(self) -> None:
        """
        Resume playback from the exact position in the queue.
        """
        if self._is_paused:
            self._is_paused = False
            self.on_state_change("speaking" if not self._output_queue.empty() else "ready")
            logger.info("Audio playback RESUMED.")

    def handle_voice_interruption(self, old_response_id: int) -> int:
        """
        Student interrupted Thinko!
        Immediately flush the entire output queue and discard in-flight chunks.
        Increments response_id to ignore trailing packets from previous turn.
        """
        self._current_response_id = max(self._current_response_id + 1, old_response_id + 1)
        dropped = 0
        while not self._output_queue.empty():
            try:
                self._output_queue.get_nowait()
                dropped += 1
            except asyncio.QueueEmpty:
                break

        self.dropped_chunks_on_interruption += dropped
        self._is_playing = False
        self.on_state_change("listening")
        logger.info(
            f"Interruption handled: flushed {dropped} queued chunks. "
            f"Active response ID incremented to #{self._current_response_id}."
        )
        return self._current_response_id

    async def _playback_dispatcher(self) -> None:
        """
        Consumes chunks from the output queue and streams them to the speaker/ESP32.
        Pauses dispatching when _is_paused is True without clearing the queue.
        """
        try:
            while self._running:
                # If paused, wait until resumed
                if self._is_paused:
                    await asyncio.sleep(0.05)
                    continue

                try:
                    chunk, r_id = await asyncio.wait_for(self._output_queue.get(), timeout=0.35)
                except asyncio.TimeoutError:
                    if self._is_playing:
                        self._is_playing = False
                        self.on_state_change("listening")
                    continue

                # Discard chunk if it belongs to an interrupted/stale turn
                if r_id < self._current_response_id:
                    continue

                if not self._is_playing:
                    self._is_playing = True
                    self.on_state_change("speaking")

                self.total_chunks_played += 1
                self.on_send_output_chunk(chunk, r_id)

                # Each 24 kHz 16-bit mono sample is 2 bytes.
                # Chunk playback duration = len(chunk) / (24000 * 2) seconds.
                duration = len(chunk) / 48000.0
                # Pace slightly faster than real-time (0.8x duration) to prevent buffer starvation on client
                await asyncio.sleep(max(0.01, duration * 0.85))

        except asyncio.CancelledError:
            pass
        except Exception as e:
            logger.error(f"Error in playback dispatcher: {e}")
